const cards = Object.entries(babyWeekContent).map(([week, content]) => {
  const w = Number(week);
  const start = (w - 1) * 7;
  const end = w * 7 - 1;

  return {
    slug: `baby-week-${w}`,
    title: content.title,
    subtitle: content.subtitle,
    card_type: cardType,
    category: "Baby / This week",
    life_stage: lifeStageForWeek(w),
    start_age_days: start,
    end_age_days: end,
    pregnancy_week_start: null,
    pregnancy_week_end: null,
    priority: 100,
    short_summary: content.summary,
    wish_i_knew: content.wish,
    what_to_do_now: content.doNow,
    conditions: { born_only: true },
    illustration_prompt: `Cute pixel art collectible: ${content.prompt}`,
    image_url: `/card-images/pixel/px-baby-week-${w}.png`,
    image_alt: `Pixel art illustration for baby week ${w}.`,
    image_status: "needed",
    status: "in_review",
  };
});

writeAnchorSeed({
  outPath: path.join(path.resolve(import.meta.dirname, ".."), "supabase", "seed_baby_weekly_anchors.sql"),
  headerComment: "Baby weekly anchor cards (weeks 1–52). Safe to re-run (upserts by slug).",
  cards,
});

console.log(`Wrote ${cards.length} baby anchor cards`);
