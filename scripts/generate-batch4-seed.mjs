function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlBool(value) {
  return value ? "true" : "false";
}

function timingFields(card) {
  if (card.start_age_days != null) {
    return `${card.start_age_days}, ${card.end_age_days}, null, null`;
  }
  return `null, null, ${card.pregnancy_week_start}, ${card.pregnancy_week_end}`;
}

function needsEditorialReview(card) {
  return Boolean(
    card.medical_sensitivity ||
      card.government_sensitivity ||
      card.safety_sensitivity ||
      card.allergy_sensitivity ||
      card.feeding_sensitivity ||
      String(card.source_notes ?? "").toLowerCase().includes("review"),
  );
}

function imageFields(card, imageMeta) {
  const relativeUrl = `/card-images/pixel/px-${card.slug}.png`;
  const imagePath = path.join(root, "public", relativeUrl);
  const hasImage = fs.existsSync(imagePath);
  const hasAlt = Boolean(imageMeta?.alt?.trim());
  return {
    hasPublishableImage: hasImage && hasAlt,
    imageUrl: hasImage ? relativeUrl : null,
    imageAlt: hasAlt ? imageMeta.alt : null,
    imageStatus: hasImage && hasAlt ? "approved" : "needed",
  };
}

function publishFields(card, hasPublishableImage) {
  if (needsEditorialReview(card) || !hasPublishableImage) {
    return `'in_review',\n  null,\n  null,\n  null`;
  }

  return `'published',\n  current_date,\n  current_date + interval '12 months',\n  now()`;
}

